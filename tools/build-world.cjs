/* Builds js/world-data.js (continents > towns > gyms) from the main app's app-catalog.js.
   Run from the repo root:  node gym-quest/tools/build-world.cjs
   - stream  = G1 / G2 / G3 (one continent each)
   - level   = Sec 1..4 (a town unlocks for students at that level or above)
   - town    = a topic (chapter);  gym = a sub topic (one catalogue entry, or an override below)
   Gym ids look like  G1.1.numbers.2  and are the keys of the question banks. */
'use strict';
const fs = require('fs'), path = require('path');
global.window = {};
require(path.join(__dirname, '..', '..', 'app-catalog.js'));
const C = window.MR_APP_CATALOG;

const slug = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Hand-written sub topic lists where the catalogue only has one entry for a whole chapter.
// Key = "<stream>.<level>.<chapter name>"
const OVERRIDES = {
  'G1.1.Numbers': ['Place value and whole numbers', 'Factors and multiples', 'Negative numbers', 'Approximation and rounding'],
  'G1.1.Four Operations': ['Adding and subtracting whole numbers', 'Multiplying and dividing whole numbers', 'Order of operations'],
  'G1.1.Ratio': ['Simplifying ratios', 'Equivalent ratios', 'Sharing in a ratio'],
  'G1.2.Linear Equations in One Variable': ['One-step and two-step equations', 'Equations with brackets', 'Unknowns on both sides'],
  'G1.3.Indices and Standard Form': ['Laws of indices', 'Zero and negative indices', 'Standard form']
};

const towns = {};   // key -> town
for (const e of C) {
  const m = /^(?:Lower|Upper)SecG([123])$/.exec(e.course || '');
  if (!m || !e.chapter || !e.year) continue;
  if (/formulae|formula sheet|reference/i.test(e.title)) continue;
  const stream = 'G' + m[1], level = parseInt(e.year.replace(/\D/g, ''), 10);
  const cm = /^Chapter\s+(\d+)\s*·\s*(.+)$/.exec(e.chapter);
  if (!cm) continue;
  const chNo = +cm[1], chName = cm[2].trim();
  const key = stream + '.' + level + '.' + chName;
  const t = towns[key] || (towns[key] = {stream, level, chNo, name: chName, raw: []});
  const sm = /^(\d+)\.(\d+)/.exec(e.title);
  t.raw.push({
    sec: sm ? +sm[1] * 100 + +sm[2] : 9999,
    name: e.title.replace(/^\d+(?:\.\d+[a-z]?)?(?:[–-]\d+(?:\.\d+[a-z]?)?)?\s+/, '').trim()
  });
}

const out = {continents: []};
for (const stream of ['G1', 'G2', 'G3']) {
  const list = Object.keys(towns).filter(k => towns[k].stream === stream).map(k => ({k, t: towns[k]}))
    .sort((a, b) => a.t.level - b.t.level || a.t.chNo - b.t.chNo);
  const cont = {stream, towns: []};
  for (const {k, t} of list) {
    let names = OVERRIDES[k];
    if (!names) {
      names = []; const seen = new Set();
      t.raw.sort((a, b) => a.sec - b.sec).forEach(r => { const n = r.name.replace(/\s+/g, ' '); if (!seen.has(n.toLowerCase())) { seen.add(n.toLowerCase()); names.push(n); } });
    }
    const id = stream + '.' + t.level + '.' + slug(t.name);
    cont.towns.push({id, name: t.name, level: t.level, chNo: t.chNo, gyms: names.map((n, i) => ({id: id + '.' + (i + 1), name: n}))});
  }
  out.continents.push(cont);
}
const dest = path.join(__dirname, '..', 'js', 'world-data.js');
fs.writeFileSync(dest, '/* generated by tools/build-world.cjs - do not edit by hand */\nwindow.GQ_WORLD = ' + JSON.stringify(out) + ';\n');
for (const c of out.continents) {
  const byLevel = {};
  c.towns.forEach(t => { const b = byLevel[t.level] || (byLevel[t.level] = {towns: 0, gyms: 0}); b.towns++; b.gyms += t.gyms.length; });
  console.log(c.stream, JSON.stringify(byLevel), 'total gyms', c.towns.reduce((n, t) => n + t.gyms.length, 0));
}
